y=10
list_x=[9,10,11]
for x in list_x:

	print(f'xの値：{x}, yの値：{y}')
	
	print(f'x は y より大きい：{x>y}')
	print(f'x は y 以上：{x>=y}')
	print(f'x は y と等しい：{x==y}')
	print(f'x は y 以下：{x<=y}')
	print(f'x は y より小さい：{x<y}')
	print('------')
